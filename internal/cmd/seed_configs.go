// seedConfigNames is the closed set of starter configs --init seeds; nothing else in a
// clone's .agentfactory/ (secrets, telemetry.json, gate files) is ever read. There is no
// copy of them inside af: each agentfactory variant's clone names its own agents, so a
// copy would be wrong for the other variant.
var seedConfigNames = []string{"agents.json", "dispatch.json", "factory.json", "litellm.yaml", "messaging.json", "models.json", "startup.json"}

const builtinRoleDirective = "Your standing rulings and newest notes are in this session's memory block; look up others by need with af memory list --type <type> or af memory list --formula <formula>. Read your docs, and prove it. Record durable learnings with af memory add."

// builtinRoleEntries are the agents.json entries of the roles af embeds without a formula
// (builtinIdentities). A fresh factory's agents.json holds only these (ADR-020): the rest of
// a roster is generated by `af install --agents` and belongs to the repository it was
// generated in.
var builtinRoleEntries = map[string]config.AgentEntry{
	"manager":    {Type: "interactive", Description: "Interactive agent for human-supervised work", Directive: builtinRoleDirective},
	"supervisor": {Type: "autonomous", Description: "Autonomous agent for independent task execution", Directive: builtinRoleDirective},
}

func builtinAgentsConfig() *config.AgentConfig {
	cfg := &config.AgentConfig{Agents: make(map[string]config.AgentEntry, len(builtinRoleEntries))}
	for role, entry := range builtinRoleEntries {
		cfg.Agents[role] = entry
	}
	return cfg
}

const noSourceTreeReason = "no agentfactory source tree"

var errNoSourceTree = errors.New(noSourceTreeReason)

// builtinSeed returns the content af itself owns for name: the built-in roles' agents.json
// on every channel and, with no source file to derive from, the messaging.json and
// factory.json a factory cannot run without (the mail router and root discovery fail
// without them).
func builtinSeed(name string, fallback bool) ([]byte, bool, error) {
	switch {
	case name == "agents.json":
		data, err := marshalSanitized(builtinAgentsConfig())
		return data, true, err
	case fallback && name == "messaging.json":
		data, err := marshalSanitized(&config.MessagingConfig{Groups: map[string][]string{"all": sortedMapKeys(builtinRoleEntries)}})
		return data, true, err
	case fallback && name == "factory.json":
		return []byte(config.DefaultFactoryConfigJSON()), true, nil
	}
	return nil, false, nil
}

// baseConfigContent selects the bytes for one seed config name: af's own content where
// builtinSeed has it, else the resolved agentfactory source clone's working-tree file.
// fallback is the single run-level "no source tree resolved" decision from
// resolveAFSource; under it every clone-derived member reports errNoSourceTree. A missing
// or malformed file under a resolved source is a hard error (source/commit skew), except
// that a messaging.json or factory.json the clone lacks gets af's own content, labeled as
// absent from the clone: refusing the whole bootstrap for a file af can write itself would
// leave the factory worse off than having no clone at all.
func baseConfigContent(name, afSrc string, fallback bool) ([]byte, string, error) {
	if data, ok, err := builtinSeed(name, fallback); ok || err != nil {
		return data, "built-in", err
	}
	if fallback {
		return nil, "", errNoSourceTree
	}
	path := filepath.Join(afSrc, ".agentfactory", name)
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		if builtin, ok, builtinErr := builtinSeed(name, true); ok || builtinErr != nil {
			return builtin, "built-in; absent from source clone " + path, builtinErr
		}
	}
	if err != nil {
		return nil, "", fmt.Errorf("reading %s from resolved source: %w", path, err)
	}
	// Scoped to the JSON-named members: litellm.yaml is YAML and must pass through
	// unvalidated (decisions.md D2). This is a light syntax check only.
	if strings.HasSuffix(name, ".json") && !json.Valid(data) {
		return nil, "", fmt.Errorf("%s under resolved source is not valid JSON: %s", name, path)
	}
	return data, "source clone: " + path, nil
}

// seedWithheldReason names why a member absent from this factory is still not seeded
// this run, or returns "" to seed it. litellm.yaml's gateway lanes pair with the codex
// profile of the models.json seeded alongside it. Next to an older models.json, a
// seeded litellm.yaml would stop quickstart's --litellm setup from writing its own
// gateway config, and the seeded one does not serve the model quickstart then
// configures for that factory.
func seedWithheldReason(name string, existing map[string]bool) string {
	if name == "litellm.yaml" && existing["models.json"] {
		return "models.json pre-exists"
	}
	return ""
}

// futureRoster is the roster a factory holds once `af install --agents` has run: base plus
// one agent per embedded formula, named after it as agent-gen names it. A seeded
// startup.json or dispatch.json names those agents before they exist, so it is checked
// against this roster; the entries carry Formula because a dispatch workflow phase must map
// to a formula-bearing agent.
func futureRoster(base *config.AgentConfig) (*config.AgentConfig, error) {
	formulas, err := availableFormulaNames()
	if err != nil {
		return nil, err
	}
	roster := &config.AgentConfig{Agents: make(map[string]config.AgentEntry, len(formulas)+len(base.Agents))}
	for name := range formulas {
		roster.Agents[name] = config.AgentEntry{Formula: name}
	}
	for name, entry := range base.Agents {
		roster.Agents[name] = entry
	}
	return roster, nil
}

// errSeedSanitizerGap carries checkSeedDispatchInert's closing clause, so its refusals read
// as before while withCloneRemedy can tell that this binary's sanitizer, not the clone, is at
// fault.
var errSeedSanitizerGap = errors.New("refusing to write it")

// withCloneRemedy appends the remedy for a refused member to err. Only the clone
// channel gets one: every remedy names the clone, which the no-source channel never
// reads, so there it has no clone to point at.
// An ABSENT member means the checkout lacks it; anything else — a member that exists but
// cannot be read (permissions, a directory in its place) as much as invalid content — is
// something to fix in place, or a clone newer than this binary. Matched on fs.ErrNotExist
// rather than *fs.PathError, which an unreadable-but-present member also satisfies: telling
// an operator to "restore" a file that is sitting right there sends them after the wrong fault.
func withCloneRemedy(err error, name, afSrc string, fallback bool) error {
	if fallback {
		return err
	}
	member := filepath.Join(afSrc, ".agentfactory", name)
	if errors.Is(err, errSeedSanitizerGap) {
		return fmt.Errorf("%w — this af binary's seed sanitizer left a dispatcher trigger armed (an af bug: report it); until af is fixed, remove that trigger from %s", err, member)
	}
	if errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("%w — restore %s (incomplete agentfactory checkout), or point AF_SOURCE_ROOT at a complete agentfactory clone", err, member)
	}
	return fmt.Errorf("%w — fix %s in the source clone, or rebuild af from that clone (make install) if it is newer than this binary", err, member)
}

// sanitizeSeed applies the foreign-project rewrites a config seeded from the
// agentfactory source clone needs before it is safe to write into a new factory —
// dispatcher triggers (repos, crons) blanked, the factory name set to this
// factory's, non-portable agent pins dropped, a telemetry "on" with no
// telemetry.json and an improvement "on" with no "on" .improvement-hook relaxed to
// "default" — passes the other seedConfigNames members through byte-identical, and
// refuses any other name. It also returns one record per rewrite that
// changed something, so the operator can see what the seed altered; records name
// keys, agents and profiles only, never profile values, which can hold tokens.
func sanitizeSeed(name string, data []byte, factoryRoot string) ([]byte, []string, error) {
	var records []string
	switch name {
	case "dispatch.json":
		decoded, err := strictDecodeRawSeed(name, data)
		if err != nil {
			return nil, nil, err
		}
		cfg := decoded.(*config.DispatchConfig)
		if len(cfg.Repos) > 0 {
			records = append(records, fmt.Sprintf("repos cleared (was: %s)", strings.Join(cfg.Repos, ", ")))
		}
		if len(cfg.Crons) > 0 {
			cronNames := make([]string, 0, len(cfg.Crons))
			for _, cron := range cfg.Crons {
				cronNames = append(cronNames, cron.Name)
			}
			records = append(records, fmt.Sprintf("crons dropped (%s)", strings.Join(cronNames, ", ")))
		}
		cfg.Repos = []string{}
		cfg.Crons = nil
		out, err := marshalSanitized(cfg)
		if err != nil {
			return nil, nil, err
		}
		if err := checkSeedDispatchInert(name, out); err != nil {
			return nil, nil, err
		}
		return out, records, nil

	case "factory.json":
		decoded, err := strictDecodeRawSeed(name, data)
		if err != nil {
			return nil, nil, err
		}
		cfg := decoded.(*config.FactoryConfig)
		if base := filepath.Base(factoryRoot); cfg.Name != base {
			records = append(records, fmt.Sprintf("name set to %q (was %q)", base, cfg.Name))
			cfg.Name = base
		}
		out, err := marshalSanitized(cfg)
		return out, records, err

	case "models.json":
		decoded, err := strictDecodeRawSeed(name, data)
		if err != nil {
			return nil, nil, err
		}
		cfg := decoded.(*config.ModelsConfig)
		var dropped []string
		for agent, profile := range cfg.Agents {
			if nonPortableProfile(cfg.Models[profile]) {
				delete(cfg.Agents, agent)
				dropped = append(dropped, agent)
			}
		}
		if len(dropped) > 0 {
			sort.Strings(dropped)
			records = append(records, fmt.Sprintf("agent pins dropped (%s)", strings.Join(dropped, ", ")))
		}
		out, err := marshalSanitized(cfg)
		return out, records, err

	case "startup.json":
		out, records, err := relaxSeededTelemetry(data, factoryRoot)
		if err != nil {
			return nil, nil, err
		}
		out, improvementRecords, err := relaxSeededImprovement(out, factoryRoot)
		return out, append(records, improvementRecords...), err

	case "agents.json", "litellm.yaml", "messaging.json":
		return data, nil, nil

	default:
		return nil, nil, fmt.Errorf("%s: not a starter config this af binary seeds", name)
	}
}

// strictDecodeRawSeed strict-decodes a member's bytes before sanitizeSeed re-encodes
// them: a tolerant decode would silently drop an unknown key on re-encode, before
// validateSeed's own strict pass could ever see it. An unknown key means the clone
// is newer than this binary; the rebuild remedy is appended once, at the seam, with
// the clone path it needs.
func strictDecodeRawSeed(name string, data []byte) (any, error) {
	decoded, err := strictDecodeSeed(name, data)
	if isUnknownFieldError(err) {
		return nil, fmt.Errorf("%w — this af binary does not know that key", err)
	}
	return decoded, err
}

// nonPortableProfile reports whether a models.json profile only works in the
// factory it came from: a non-loopback gateway endpoint, or a file: secret
// reference whose secret file is never seeded. Agent pins and the default both go
// through this one predicate so they cannot disagree about what is portable. The
// baseURL != "" gate matters: IsLoopbackEndpoint("") is false, so without it every
// plain-cloud profile (no declared endpoint) would count as non-portable.
// host.docker.internal counts as non-loopback here although localPlaceholderSecret
// treats it as local: that predicate asks whether the token can be a real secret,
// this one whether the endpoint exists for the new factory. It names the Docker host
// of the machine that wrote the config, and a pinned launch is not held to the
// fitness attestation a --model selection needs, so a kept pin would launch against a
// model server nobody checked.
func nonPortableProfile(profile map[string]string) bool {
	baseURL := profile[baseURLKey]
	nonLoopback := baseURL != "" && !config.IsLoopbackEndpoint(baseURL)
	return nonLoopback || strings.HasPrefix(profile[authTokenKey], secretPrefix)
}

// relaxSeededTelemetry rewrites a seeded "telemetry":"on" to "default" when the new
// factory has no telemetry.json: "on" would turn recording on at the first af up
// although nobody asked for it, while "default" leaves the gate alone so a later
// `af telemetry on` sticks ("off" would be re-applied over it at every af up). The
// rewrite is key-level because a typed StartupConfig round-trip would add zero-valued
// blocks the source never had. Every other case returns the input bytes untouched
// and leaves judging them to validateSeed's strict decode.
func relaxSeededTelemetry(data []byte, factoryRoot string) ([]byte, []string, error) {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return data, nil, nil
	}
	var telemetry string
	if err := json.Unmarshal(fields["telemetry"], &telemetry); err != nil || telemetry != "on" {
		return data, nil, nil
	}
	if _, err := os.Stat(config.TelemetryConfigPath(factoryRoot)); !os.IsNotExist(err) {
		return data, nil, nil
	}
	fields["telemetry"] = json.RawMessage(`"default"`)
	out, err := marshalSanitized(fields)
	return out, []string{`telemetry "on" -> "default" (no telemetry.json)`}, err
}

// relaxSeededImprovement rewrites a seeded "improvement":"on" to "default" unless the new
// factory's .improvement-hook already reads "on": the first af up would write "on" into the
// hook and arm the factory half of the improvement toggle, which --init never does (absent
// means off), while "default" leaves the hook to `af improvement on`. A hook reading "off"
// is relaxed too, or that af up would overwrite the operator's "off". Like
// relaxSeededTelemetry it is key-level and leaves every other case untouched.
func relaxSeededImprovement(data []byte, factoryRoot string) ([]byte, []string, error) {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return data, nil, nil
	}
	var improvement string
	if err := json.Unmarshal(fields["improvement"], &improvement); err != nil || improvement != "on" {
		return data, nil, nil
	}
	if improvementFactoryEnabled(factoryRoot) {
		return data, nil, nil
	}
	fields["improvement"] = json.RawMessage(`"default"`)
	out, err := marshalSanitized(fields)
	return out, []string{`improvement "on" -> "default" (.improvement-hook not on)`}, err
}

// marshalSanitized re-encodes a sanitized config, matching every existing
// Save*Config function's own idiom (json.MarshalIndent with a 2-space indent
// plus a trailing newline).
func marshalSanitized(v any) ([]byte, error) {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("re-encoding sanitized config: %w", err)
	}
	return append(data, '\n'), nil
}

// checkSeedDispatchInert refuses a sanitized dispatch.json the dispatcher would act on. Blanking
// the trigger sections the sanitizer knows is not enough on its own: a trigger section added to
// DispatchConfig later would pass through untouched and poll the source repo's work queue from
// the new factory, so the loader's own verdict is the gate, not the sanitizer's key list.
func checkSeedDispatchInert(name string, data []byte) error {
	_, err := config.ParseDispatchConfig(data)
	if errors.Is(err, config.ErrMissingField) {
		return nil
	}
	if err == nil {
		return fmt.Errorf("%s: the sanitized seed would still arm the dispatcher; %w", name, errSeedSanitizerGap)
	}
	return fmt.Errorf("%s: the sanitized seed would arm the dispatcher with an invalid config (%v); %w", name, err, errSeedSanitizerGap)
}

// strictDecodeSeed strict-decodes one seed's bytes (raw in sanitizeSeed, sanitized in
// validateSeed) into its typed config struct, the same DisallowUnknownFields idiom
// decodeJSONStdin uses for the setter path (config_set.go) — an unknown field in a seed
// is caught before it is ever written, not just at the next `af config <x> set`.
// Scoped to the clone-derived JSON members exactly like baseConfigContent's gate
// (decisions.md D3): litellm.yaml, and agents.json, which af builds itself, return
// (nil, nil) and bypass this pass entirely; a name outside seedConfigNames is refused.
func strictDecodeSeed(name string, data []byte) (any, error) {
	var v any
	switch name {
	case "dispatch.json":
		v = &config.DispatchConfig{}
	case "startup.json":
		v = &config.StartupConfig{}
	case "messaging.json":
		v = &config.MessagingConfig{}
	case "models.json":
		v = &config.ModelsConfig{}
	case "factory.json":
		v = &config.FactoryConfig{}
	case "agents.json", "litellm.yaml":
		return nil, nil
	default:
		return nil, fmt.Errorf("%s: not a starter config this af binary seeds", name)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	return v, nil
}

// reportSeedViolation applies decisions.md D2's severity split: a violation against
// an agents.json that is itself part of the current fresh seed batch is refused
// before any file is written; a violation against a pre-existing on-disk agents.json
// is surfaced as a warning and the seed proceeds — CFG-4 warns, it does not repair
// mixed-provenance file sets (decisions.md D8).
func reportSeedViolation(name string, err error, agentsAreFresh bool, warn io.Writer) error {
	if agentsAreFresh {
		return fmt.Errorf("%s: %w", name, err)
	}
	fmt.Fprintf(warn, "warning: %s: %v\n", name, err)
	return nil
}

// availableFormulaNames is every embedded install_formulas/ member, name derived by
// stripping the ".formula.toml" suffix writeFormulas (install.go) itself writes under —
// the formulas --init installs and `af install --agents` turns into agents.
func availableFormulaNames() (map[string]bool, error) {
	entries, err := formulasFS.ReadDir("install_formulas")
	if err != nil {
		return nil, fmt.Errorf("reading embedded formulas: %w", err)
	}
	names := make(map[string]bool, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		names[strings.TrimSuffix(entry.Name(), ".formula.toml")] = true
	}
	return names, nil
}

// localPlaceholderSecret reports whether an auth token is a non-secret placeholder: a
// local model server (loopback, or the Docker host as seen from a container) accepts
// any token, so the value guards nothing. An sk- shaped value is still flagged — the
// loader accepts one on loopback, so a pasted gateway master key would otherwise go
// unwarned; the shape is inlined as session.go does, keeping config's
// looksLikeCredential unexported. host.docker.internal is matched here rather than
// added to IsLoopbackEndpoint, which would also relax the loader's literal-credential
// guard for it.
func localPlaceholderSecret(value, baseURL string) bool {
	if strings.HasPrefix(value, "sk-") {
		return false
	}
	if config.IsLoopbackEndpoint(baseURL) {
		return true
	}
	u, err := url.Parse(baseURL)
	return err == nil && u.Hostname() == "host.docker.internal"
}

// lintSeedSecrets warns — never fails, per decisions.md D5/D7 — about a models.json
// profile carrying a plaintext secret about to be written into a new factory's seed: a
// non-empty, non-"file:" ANTHROPIC_AUTH_TOKEN or *_API_KEY value. Only the auth token can be
// a local placeholder: a *_API_KEY is an upstream provider credential the gateway forwards,
// so it is real whatever endpoint the profile points at. The warning names the profile and
// key, never the value.
func lintSeedSecrets(name string, cfg *config.ModelsConfig, warn io.Writer) {
	for _, profile := range sortedMapKeys(cfg.Models) {
		values := cfg.Models[profile]
		for _, key := range sortedMapKeys(values) {
			if key != authTokenKey && !strings.HasSuffix(key, "_API_KEY") {
				continue
			}
			value := values[key]
			if value == "" || strings.HasPrefix(value, secretPrefix) {
				continue
			}
			if key == authTokenKey && localPlaceholderSecret(value, values[baseURLKey]) {
				continue
			}
			fmt.Fprintf(warn, "warning: %s: profile %q has a plaintext %s — use a %q reference or confirm this is an intentional placeholder\n",
				name, profile, key, secretPrefix)
		}
	}
}

// validateSeed runs the strict-decode + cross-file coherence pass (CFG-4) on one
// sanitized seed, ahead of Phase 4's seed-write loop calling it for every candidate
// before any write begins (decisions.md D6). agents is the reference roster
// dispatch/startup/messaging agent-refs are checked against; agentsAreFresh selects
// the severity for those three checks per decisions.md D2 (the models.json checks
// concern that file alone and are unaffected by it). warn receives non-fatal
// advisories: seed-vs-pre-existing-agents.json incoherence, and the models.json
// secret-lint.
func validateSeed(name string, data []byte, agents *config.AgentConfig, agentsAreFresh bool, warn io.Writer) error {
	decoded, err := strictDecodeSeed(name, data)
	if err != nil {
		return err
	}
	switch cfg := decoded.(type) {
	case *config.StartupConfig:
		// Hard whatever agentsAreFresh says: a startup.json the loader rejects stops every
		// af up, whichever agents.json it sits beside.
		if err := config.ValidateStartupConfig(cfg); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if err := rejectUnknownStartupAgents(cfg, agents); err != nil {
			return reportSeedViolation(name, err, agentsAreFresh, warn)
		}
	case *config.DispatchConfig:
		// The seed is written inert, so ParseDispatchConfig stops at "no repos" before these
		// rules; without them a broken mapping would surface only when a repo is added. Not
		// via reportSeedViolation, and never read as "not configured": most of these errors
		// wrap ErrMissingField too.
		if err := config.ValidateDispatchStructure(cfg); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		// models nil: the seed pass scopes to agent-ref checks only this phase
		// (decisions.md D8) — model-pin resolution against a seeded/pre-existing
		// models.json is a named, accepted residual, not attempted here.
		if err := config.ValidateDispatchConfig(cfg, agents, nil); err != nil {
			return reportSeedViolation(name, err, agentsAreFresh, warn)
		}
	case *config.MessagingConfig:
		if err := rejectUnknownGroupMembers(cfg, agents); err != nil {
			return reportSeedViolation(name, err, agentsAreFresh, warn)
		}
	case *config.ModelsConfig:
		if err := config.ValidateModelsConfig(cfg); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		// Refused rather than repaired: clearing default would break quickstart's
		// .models[.default] read, and re-pointing it would mean picking a profile
		// from config content.
		if cfg.Default != "" && nonPortableProfile(cfg.Models[cfg.Default]) {
			return fmt.Errorf("%s: default %q names a non-portable profile (gateway endpoint or file: secret reference) — set %s \"default\" to a profile with no gateway endpoint or secret reference in the source clone",
				name, cfg.Default, name)
		}
		lintSeedSecrets(name, cfg, warn)
	}
	return nil
}
